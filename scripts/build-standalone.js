const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const publicDir = path.join(root, "public");
const workerSourcePath = path.join(root, "src", "worker.js");
const outputPath = path.join(root, "src", "worker-standalone.js");

const indexHtml = fs.readFileSync(path.join(publicDir, "index.html"), "utf8");
const appVersion = indexHtml.match(/app\.js\?v=(\d+)/)?.[1] || "latest";
const stylesVersion = indexHtml.match(/styles\.css\?v=(\d+)/)?.[1] || appVersion;
const MIME_TYPES = {
  ".css": "text/css; charset=utf-8",
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".webmanifest": "application/manifest+json; charset=utf-8",
};

const assets = [
  ["/", "index.html", "text/html; charset=utf-8"],
  ["/index.html", "index.html", "text/html; charset=utf-8"],
  [`/app.js?v=${appVersion}`, "app.js", "text/javascript; charset=utf-8"],
  ["/app.js", "app.js", "text/javascript; charset=utf-8"],
  [`/styles.css?v=${stylesVersion}`, "styles.css", "text/css; charset=utf-8"],
  ["/styles.css", "styles.css", "text/css; charset=utf-8"],
  [`/default-cards.json?v=${appVersion}`, "default-cards.json", "application/json; charset=utf-8"],
  ["/default-cards.json", "default-cards.json", "application/json; charset=utf-8"],
  ["/manifest.webmanifest", "manifest.webmanifest", "application/manifest+json; charset=utf-8"],
  ["/service-worker.js", "service-worker.js", "text/javascript; charset=utf-8"],
  ["/icon.svg", "icon.svg", "image/svg+xml"],
];

let output = `// This file is generated by scripts/build-standalone.js. Edit public/* and src/worker.js instead.\n`;
output += `const STATIC_ASSETS = new Map();\n\n`;
output += `function addAsset(path, content, contentType, encoding = "text") {\n  STATIC_ASSETS.set(path, { content, contentType, encoding });\n}\n\n`;

for (const [route, fileName, contentType] of assets) {
  const content = fs.readFileSync(path.join(publicDir, fileName), "utf8");
  output += `addAsset(${JSON.stringify(route)}, ${JSON.stringify(content)}, ${JSON.stringify(contentType)});\n`;
}

for (const filePath of listFiles(path.join(publicDir, "assets"))) {
  const route = `/${path.relative(publicDir, filePath).split(path.sep).join("/")}`;
  const contentType = MIME_TYPES[path.extname(filePath).toLowerCase()] || "application/octet-stream";
  const content = fs.readFileSync(filePath).toString("base64");
  output += `addAsset(${JSON.stringify(route)}, ${JSON.stringify(content)}, ${JSON.stringify(contentType)}, "base64");\n`;
}

let workerSource = fs.readFileSync(workerSourcePath, "utf8");
workerSource = workerSource.replace("return env.ASSETS.fetch(request);", "return serveStatic(url);");

output += `\n${workerSource}`;
output += `\n\nfunction serveStatic(url) {\n`;
output += `  const asset = STATIC_ASSETS.get(url.pathname + url.search) || STATIC_ASSETS.get(url.pathname) || STATIC_ASSETS.get("/");\n`;
output += `  const body = asset.encoding === "base64" ? Uint8Array.from(atob(asset.content), (char) => char.charCodeAt(0)) : asset.content;\n`;
output += `  return new Response(body, {\n`;
output += `    headers: {\n`;
output += `      "Content-Type": asset.contentType,\n`;
output += `      "Cache-Control": url.pathname === "/service-worker.js" ? "no-cache" : "public, max-age=300",\n`;
output += `    },\n`;
output += `  });\n`;
output += `}\n`;

fs.writeFileSync(outputPath, output);
console.log(`Built ${path.relative(root, outputPath)} with app v${appVersion}.`);

function listFiles(dir) {
  if (!fs.existsSync(dir)) return [];

  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return listFiles(entryPath);
    if (entry.isFile()) return [entryPath];
    return [];
  });
}
